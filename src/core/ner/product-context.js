// Контекст продукта для одиночного имени (доработка 0.5 по прогону КП; §5.2 NLP `docs/spec-full.md`, FR-61, FR-62): «Алиса» —
// и женское имя, и голосовой помощник Яндекса. Слово — не человек, если (1) это имя голосового помощника («Алиса», «Маруся»,
// «Салют», Siri, Alexa), а перед ним — «Яндекс», «голосовой помощник/ассистент», «умная колонка», «чат-бот», «нейросеть»
// («Яндекс Алису», «голосовой помощник Алиса»); (2) любое слово стоит в перечислении продуктов между двумя продуктами
// или после продукта перед «и другие» («в GigaChat, Алису, DeepSeek и другие модели»). «В Яндексе Алиса отвечает за…»,
// «Алиса от Яндекса приедет» — неоднозначно, остаются ФИО (fail-closed). Общий для фильтра PER модели (`filters-pl.js`),
// обращений (`names/vocative.js`) и вариантов лица (`names/kb.js`). Чистый JS без chrome.* и DOM.
import { PRODUCT_NAMES, stopKey } from './stoplist.js';
import { inStoplist } from './filters.js';

/** Продукты для перечисления (ключи `stopKey`): программы, сервисы, модели ИИ — без обращений и бренда владельца. */
const PRODUCTS = new Set(PRODUCT_NAMES.map(stopKey));
/** Имена голосовых помощников во всех падежах: «Алиса/Алисы/Алисе/Алису/Алисой», «Маруся», «Салют», Siri, Alexa. */
const ASSISTANT_RE = /^(?:алис(?:а|ы|е|у|ой|ою)|марус(?:я|и|е|ю|ей|ею)|салют(?:а|у|ом|е)?|сири|siri|alexa)$/iu;
/** Перед словом — название помощника или сервиса: «Яндекс Алиса», «голосовой помощник Алиса», «умной колонке «Алиса»». */
const PRODUCT_LEAD_RE =
  /(?<![\p{L}])(?:яндекс\.?|yandex\.?|голосов\p{L}*[ \u00a0]+(?:помощник|ассистент)\p{L}*|умн\p{L}*[ \u00a0]+колонк\p{L}*|чат-?бот\p{L}*|нейросет\p{L}*|(?:ии|ai)-?(?:помощник|ассистент)\p{L}*)[ \u00a0]*[«"“„]?$/iu;
/** Соседи в перечислении: слово перед «,»/«и»/«или» слева и после них справа. */
const LIST_LEFT_RE = /([\p{L}\p{N}][\p{L}\p{N}.+-]*)[»"”]?[ \u00a0]*(?:,|[ \u00a0]и|[ \u00a0]или)[ \u00a0]*$/u;
const LIST_RIGHT_RE = /^[ \u00a0]*(?:,|и(?=[ \u00a0])|или(?=[ \u00a0]))[ \u00a0]*[«"“„]?([\p{L}\p{N}][\p{L}\p{N}.+-]*)/u;
/** Конец перечисления: «и другие», «и др.», «и т. п.», «etc». */
const LIST_END_RE = /^[ \u00a0]*,?[ \u00a0]*(?:(?:и|или)[ \u00a0]+(?:други\p{L}*|др\.|прочи\p{L}*|т\.[ \u00a0]*[дп]\.)|etc\.?|and[ \u00a0]+others)/iu;
const isProduct = (w) => !!w && inStoplist(stopKey(w), PRODUCTS, w);

/**
 * Одно слово в контексте продукта: имя помощника после «Яндекс», «голосовой помощник», «умная колонка», «чат-бот»,
 * «нейросеть»; любое слово в перечислении между двумя продуктами («GigaChat, Алису, DeepSeek») или после продукта перед
 * «и другие». Один продукт по соседству не в счёт («Excel, Мария, пришлите…»).
 * @param {string} text @param {number} start @param {number} end
 */
export function productContext(text, start, end) {
  const before = text.slice(Math.max(0, start - 40), start);
  const after = text.slice(end, end + 40);
  if (ASSISTANT_RE.test(text.slice(start, end)) && PRODUCT_LEAD_RE.test(before)) return true;
  const left = LIST_LEFT_RE.exec(before);
  if (!left || !isProduct(left[1])) return false;
  const right = LIST_RIGHT_RE.exec(after);
  return (!!right && isProduct(right[1])) || LIST_END_RE.test(after);
}

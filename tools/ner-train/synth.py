def _render(rng, lx, tpl, lang):
    tokens, tags = [], []
    for part in PLACEHOLDER_RE.split(tpl):
        if part.startswith("{"):
            text, typ = _span(rng, lx, part[1:-1], lang)
        else:
            text, typ = part, None
        words = TOKEN_RE.findall(text)
        tokens += words
        tags += ["O"] * len(words) if typ is None else [f"B-{typ}"] + [f"I-{typ}"] * (len(words) - 1)
    return tokens, tags


def sentence(rng, lang, lx=None):
    """One contract-style sentence (the 1.0.0 templates)."""
    lx = lx or Lex("train")
    return _render(rng, lx, rng.choice(RU_TEMPLATES if lang == "ru" else EN_TEMPLATES), lang)


_GENRE_POOLS = {g: {"pos": [t for t in ts if not is_negative(t)], "neg": [t for t in ts if is_negative(t)]}
                for g, (_, ts) in GENRES.items()}


def genre_sentence(rng, lx, negative_share):
    """One genre sentence; returns tokens, tags, lang, genre."""
    genres = list(GENRE_WEIGHTS)
    genre = rng.choices(genres, weights=[GENRE_WEIGHTS[g] for g in genres])[0]
    lang = GENRES[genre][0]
    pool = _GENRE_POOLS[genre]["neg" if rng.random() < negative_share else "pos"]
    toks, tags = _render(rng, lx, rng.choice(pool), lang)
    return toks, tags, lang, genre


def _rows(labels):
    return {"tokens": [], "ner_tags": [], "lang": [], "genre": [], "negative": []}, {l: i for i, l in enumerate(labels)}


def _append(rows, l2i, toks, tags, lang, genre):
    rows["tokens"].append(toks)
    rows["ner_tags"].append([l2i[t] for t in tags])
    rows["lang"].append(lang)
    rows["genre"].append(genre)
    rows["negative"].append(all(t == "O" for t in tags))


def generate(n: int, seed: int, labels: list[str], genre_share: float = 0.0, negative_share: float = 0.45,
             part: str = "train", en_share_contract: float = 0.25, block: set | None = None) -> Dataset:
    """n synthetic sentences: a genre_share of genre templates, the rest contract templates (1.0.0).
    block: proper-name words of the evaluation corpus; word-list items containing them are not used."""
    rng = random.Random(seed)
    lx = Lex(part, block)
    rows, l2i = _rows(labels)
    for _ in range(n):
        if rng.random() < genre_share:
            toks, tags, lang, genre = genre_sentence(rng, lx, negative_share)
        else:
            lang = "ru" if rng.random() >= en_share_contract else "en"
            toks, tags = sentence(rng, lang, lx)
            genre = "contract" if lang == "ru" else "contract_en"
        _append(rows, l2i, toks, tags, lang, genre)
    return Dataset.from_dict(rows)


def generate_genre_test(n: int, seed: int, labels: list[str], negative_share: float, exclude: set,
                        block: set | None = None) -> Dataset:
    """Held-out genre sentences (test partition of the word lists), none equal to a sentence in `exclude`."""
    rng = random.Random(seed)
    lx = Lex("test", block)
    rows, l2i = _rows(labels)
    seen = set()
    attempts = 0
    while len(rows["tokens"]) < n:
        attempts += 1
        assert attempts < 50 * n, "cannot build a held-out genre set without overlaps"
        toks, tags, lang, genre = genre_sentence(rng, lx, negative_share)
        key = tuple(toks)
        if key in exclude or key in seen:
            continue
        seen.add(key)
        _append(rows, l2i, toks, tags, lang, genre)
    return Dataset.from_dict(rows)


